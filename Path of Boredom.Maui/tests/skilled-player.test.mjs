import assert from 'node:assert/strict';
import { startRun } from '../../Path of Boredom.Game/wwwroot/js/arpg-engine.js';
import { createSkilledPlayer, threatScore, spendProgression } from './skilled-player.mjs';
const state = startRun(() => 0.5, 'inferno', 'ranger');
state.resumeDelay = 0;
state.projectiles = [{ x: 450, y: 325, vx: 200, vy: 0, life: 3, damage: 30 }];
assert.ok(threatScore(state, { x: 550, y: 325, radius: 16 }, 0.5) > 0, 'predict projectile crossing');
assert.equal(threatScore(state, { x: 550, y: 200, radius: 16 }, 0.5), 0);
state.player.level = 10;
state.gold = 600;
const health = state.player.health, damage = state.player.damage, gold = state.gold;
spendProgression(state);
assert.equal(state.status, 'playing');
assert.equal(state.player.damage, damage, 'no injected base damage');
assert.ok(state.player.health >= health, 'legal armor purchases may heal');
assert.ok(state.gold < gold && state.runSystems.summary.spent === gold - state.gold);
assert.ok(Object.values(state.skillTree).some(tree => Object.values(tree).some(rank => rank > 0)));
const controller = createSkilledPlayer();
const first = controller(state);
state.time += 0.05;
const next = controller(state);
assert.equal(next.x, first.x); assert.equal(next.y, first.y);
assert.equal(next.dodge, false); assert.equal(next.potion, false);
assert.ok(Math.abs(first.x) <= 1 && Math.abs(first.y) <= 1);
console.log('PASS: projectile prediction, safe points, legal progression spending, unchanged base damage and 150ms movement decision interval');
